  const dicts = { tr, en };
  let lang = "en";

  function resolve(setting) {
    if (setting === "tr" || setting === "en") return setting;
    const sys = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
    return sys.toLowerCase().startsWith("tr") ? "tr" : "en";
  }

  function t(key, ...args) {
    const v = dicts[lang][key] ?? dicts.en[key];
    if (v === undefined) return key;
    return typeof v === "function" ? v(...args) : v;
  }

  function applyStatic(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
    root.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle)));
    root.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  }

  window.i18n = {
    t,
    resolve,
    applyStatic,
    get lang() { return lang; },
    set(setting) {
      lang = resolve(setting);
      document.documentElement.lang = lang;
      applyStatic();
      return lang;
    },
  };
